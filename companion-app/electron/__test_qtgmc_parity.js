// Cross-language QTGMC emission parity — the companion side of
// tests/fixtures/qtgmc_parity.json (the native composer test
// test_chain_compose/qtgmc_parity_fixture reads the SAME file).
//
// WHY THIS IS A SECURITY TEST: approval binds the executable content
// (security re-review). An Approve click in the companion stores
// `approvedContent` = the DRAFT emitter's body; the native composer re-emits
// the body and runs the step only on a byte-for-byte match. If the two
// emitters ever disagree — preset whitelist, argument order, integer-vs-float
// handling, float formatting — either the approved step silently stops
// running, or (worse) a mismatch is masked by a weaker check. This test
// makes any divergence a loud failure.
//
// Also pins pyFloat against native std::setprecision(max_digits10) cases and
// script-body byte parity (no-op default, trailing-newline normalization).
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const tsTmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vsres-qtgmc-parity-'));
function compileTs(rel) {
    const src = path.join(__dirname, '..', 'shared', rel);
    const tscBin = path.join(__dirname, '..', 'node_modules', 'typescript', 'bin', 'tsc');
    const r = spawnSync(process.execPath, [tscBin, src,
        '--outDir', tsTmp, '--module', 'commonjs', '--target', 'es2022', '--skipLibCheck'],
        { stdio: 'pipe' });
    if (r.status !== 0) throw new Error('tsc failed: ' + r.stderr);
    return require(path.join(tsTmp, rel.replace(/\.ts$/, '.js')));
}

const { executableTextForStep, emitQtgmcBody, pyFloat, scriptBody } = compileTs('draft-composer.ts');
const fixturePath = path.join(__dirname, '..', '..', 'tests', 'fixtures', 'qtgmc_parity.json');
const fixture = JSON.parse(fs.readFileSync(fixturePath, 'utf8'));

test('qtgmc parity fixture: draft emitter matches every pinned native body byte-for-byte', () => {
    assert.ok(Array.isArray(fixture) && fixture.length > 0, 'fixture present');
    for (const entry of fixture) {
        const body = executableTextForStep({ type: 'qtgmc', params: entry.params });
        assert.equal(body, entry.expected,
            `case ${entry.name}: draft body must equal the native pinned body`);
    }
});

test('qtgmc parity fixture cases cover the exposed preset set (no silent Slower substitution)', () => {
    // Every preset the UI exposes must be emittable verbatim from the draft
    // path — Placebo/Draft previously previewed as Slower (correctness review C12).
    const presets = ['Placebo', 'Very Slow', 'Slower', 'Slow', 'Medium', 'Fast', 'Faster', 'Draft', 'Ultra Fast'];
    for (const preset of presets) {
        const body = emitQtgmcBody({ preset, tff: true, fpsDivisor: 2 });
        assert.ok(body.includes(`Preset='${preset}'`), `preset ${preset} emitted verbatim`);
    }
    // Unknown/invalid presets still fall back (native sanitize_preset).
    assert.ok(emitQtgmcBody({ preset: 'Nonsense', tff: true }).includes("Preset='Slower'"));
    assert.ok(emitQtgmcBody({ preset: 7, tff: true }).includes("Preset='Slower'"));
    assert.ok(emitQtgmcBody({ preset: "'); import os #", tff: true }).includes("Preset='Slower'"));
});

test('pyFloat mirrors native std::setprecision(max_digits10) output', () => {
    // Expected strings generated by the native py_float under the same
    // cases as the fixture; pinned here for the values the fixture cannot
    // carry (>2 ints etc. are carried through Sharpness, these are the
    // direct formatter cases).
    const cases = [
        [2, '2.0'],
        [0.1, '0.10000000000000001'],
        [0.25, '0.25'],
        [0.5, '0.5'],
        [2.5, '2.5'],
        [1 / 3, '0.33333333333333331'],
        [1e-7, '9.9999999999999995e-08'],
        [1e-5, '1.0000000000000001e-05'],
        [1e-9, '1.0000000000000001e-09'],
        [1e20, '1e+20'],
        [1e17, '1e+17'],
        [123456789.5, '123456789.5'],
        [-1.5, '-1.5'],
        [0.3, '0.29999999999999999'],
        [0.6, '0.59999999999999998'],
    ];
    for (const [value, expected] of cases) {
        assert.equal(pyFloat(value), expected, `pyFloat(${value})`);
    }
    // Round-trip: every emitted token must parse back to the exact double.
    for (const [value] of cases) {
        assert.equal(Number(pyFloat(value)), value, `pyFloat(${value}) round-trips`);
    }
});

test('script bodies are byte-identical to the native script filter rules', () => {
    // Mirror of ScriptFilter::emit: code verbatim + exactly one trailing
    // newline; missing/non-string code → shared no-op comment default.
    assert.equal(scriptBody({ code: 'clip = clip' }), 'clip = clip\n');
    assert.equal(scriptBody({ code: 'clip = clip\n' }), 'clip = clip\n');
    assert.equal(scriptBody({ code: 'a\nb' }), 'a\nb\n');
    assert.equal(scriptBody({}), '# empty script step\n');
    assert.equal(scriptBody({ code: 7 }), '# empty script step\n');
    assert.equal(scriptBody({ code: '' }), '\n');
    assert.equal(executableTextForStep({ type: 'script', params: { code: 'x' } }), 'x\n');
    assert.equal(executableTextForStep({ type: 'mystery', params: {} }), null);
});

test('wrong-typed qtgmc fields fall back to native defaults (no throw, no drift)', () => {
    assert.equal(emitQtgmcBody({ tff: 'false' }), "clip = havs.QTGMC(clip, Preset='Slower', TFF=True, FPSDivisor=2)\n");
    assert.equal(emitQtgmcBody({ fpsDivisor: '2' }), "clip = havs.QTGMC(clip, Preset='Slower', TFF=True, FPSDivisor=2)\n");
    assert.equal(emitQtgmcBody({ inputType: 5, tff: true }), "clip = havs.QTGMC(clip, Preset='Slower', TFF=True, FPSDivisor=2)\n");
    assert.equal(emitQtgmcBody({ tr2: 2.5, tff: false }), "clip = havs.QTGMC(clip, Preset='Slower', TFF=False, FPSDivisor=2)\n");
    assert.equal(emitQtgmcBody({ sourceMatch: 0, tff: false }), "clip = havs.QTGMC(clip, Preset='Slower', TFF=False, FPSDivisor=2)\n");
    assert.equal(emitQtgmcBody({ tff: null, fpsDivisor: null, inputType: null, preset: null }),
        "clip = havs.QTGMC(clip, Preset='Slower', TFF=True, FPSDivisor=2)\n");
});
