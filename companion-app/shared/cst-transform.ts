// CST (Color Space Transform) — structured script step.
//
// DESIGN CONTRACT (docs/color-management-capabilities.md):
//   - MANUAL transform: the OFX API exposes NO node-input color metadata, so
//     there is NO automatic detection. Unknown stays unknown; the operator
//     states the input interpretation explicitly.
//   - Gamut (primaries), transfer function, RGB↔YUV matrix and range are
//     SEPARATE controls and clearly labeled in the emitted code.
//   - Unsupported combinations are REJECTED with a useful error at emit
//     time — never silently treated as Rec.709.
//   - Float precision: all transfer/gamut math runs on RGBS (float32).
//   - Duration, frame rate and dimensions are never touched.
//   - VS R75 resize has NO transfer_s support (verified against the staged
//     runtime) — transfers are implemented directly as std.Expr RPN per
