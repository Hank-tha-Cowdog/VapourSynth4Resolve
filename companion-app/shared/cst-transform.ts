// YUV matrix string VS resize accepts (matrix_in_s/matrix_s), or null for
// "auto — read frame props (_Matrix/_ColorRange)". Only these are supported;
// anything else is rejected at emit time.
export const CST_MATRICES: Record<string, string | null> = {
    auto: null, '601': '170m', '709': '709', '2020ncl': '2020ncl', '470bg': '470bg',
};
export const CST_RANGES: Record<string, string | null> = {
    auto: null, limited: 'limited', full: 'full',
};
export const CST_GAMUTS = ['709', '2020', 'p3d65', '170m'] as const;
export const CST_OUT_FORMATS: Record<string, string> = {
    '420': 'YUV420P16', '422': 'YUV422P16', '444': 'YUV444P16',
};

export const CST_DEFAULT_PARAMS: Record<string, unknown> = {
    label: 'CST',
    inPrimaries: '709', inTransfer: '1886', inMatrix: 'auto', inRange: 'auto',
    outPrimaries: '709', outTransfer: '1886', outMatrix: '709', outRange: 'limited',
    outSubsampling: '420', rangePolicy: 'clamp',
};

const GAMUT_LABEL: Record<string, string> = {
    '709': 'Rec.709/sRGB', '2020': 'Rec.2020', 'p3d65': 'DCI-P3 (D65)', '170m': 'SMPTE-C (NTSC 525)',
};
const XFER_LABEL: Record<string, string> = {
    linear: 'Linear', '1886': 'BT.1886 (2.4 power)', '709oetf': 'BT.709 (camera OETF)',
    srgb: 'sRGB', pq: 'PQ (ST.2084, 0–1)', hlg: 'HLG (STD-B67)',
};
const MAT_LABEL: Record<string, string> = {
    auto: 'auto (frame props)', '601': 'Rec.601 (170m)', '709': 'Rec.709',
    '2020ncl': 'Rec.2020 ncl', '470bg': 'BT.470BG (PAL)', rgb: 'keep RGB (float RGBS)',
};

function pick(allowed: readonly string[], params: Record<string, unknown>,
               key: string, what: string): string {
    const raw = params[key];
    const val = typeof raw === 'string' ? raw : undefined;
    if (val === undefined) {
        throw new Error('CST: ' + what + ' is required (got ' + JSON.stringify(raw) + '). '
            + 'Supported: ' + allowed.join(', ') + '.');
    }
    if (!allowed.includes(val)) {
        throw new Error('CST: unsupported ' + what + ' "' + val + '" — supported: '
            + allowed.join(', ') + '. NOT silently treated as any default; fix the parameter.');
    }
    return val;
}

/**
 * params → the CST step's Python body. The emitted script:
 *   - decodes YUV→RGBS float (explicit or auto matrix/range via VS props),
 *   - applies the out-of-range policy (clamp [0,1] default — the transfer
 *     curves are undefined outside [0,1]; 'pass' is opt-in and documented),
 *   - decodes the input transfer → linear,
 *   - applies the gamut 3×3 (published-verified pair table) via
 *     ShufflePlanes + std.Expr (plane-mixing, verified pattern),
 *   - encodes the output transfer,
 *   - encodes RGB→YUV (matrix/range/subsampling) or keeps float RGB.
 * Identity stages (linear↔linear, same gamut) are skipped — honest
 * simplification with a comment naming what was skipped.
 */
export function emitCstBody(params: Record<string, unknown>): string {
    const gamuts = CST_GAMUTS as readonly string[];
    const inPrim = pick(gamuts, params, 'inPrimaries', 'input primaries');
    const outPrim = pick(gamuts, params, 'outPrimaries', 'output primaries');
    const xfers = Object.keys(CST_TRANSFERS);
    const inXf = pick(xfers, params, 'inTransfer', 'input transfer');
    const outXf = pick(xfers, params, 'outTransfer', 'output transfer');
    const inMat = pick(Object.keys(CST_MATRICES), params, 'inMatrix', 'input matrix');
    const inRng = pick(Object.keys(CST_RANGES), params, 'inRange', 'input range');
    // Output matrix: explicit YUV matrix or 'rgb' — 'auto' is INPUT-only
    // (an "auto" output would emit matrix_s='null' — rejected, not defaulted).
    const outMats = [...Object.keys(CST_MATRICES).filter(k => k !== 'auto'), 'rgb'];
    const outMat = pick(outMats, params, 'outMatrix', 'output matrix');
    const outRng = pick(Object.keys(CST_RANGES), params, 'outRange', 'output range');
    const outSub = pick(Object.keys(CST_OUT_FORMATS), params, 'outSubsampling', 'output subsampling');
    const policy = typeof params.rangePolicy === 'string' ? params.rangePolicy : 'clamp';
    if (policy !== 'clamp' && policy !== 'pass') {
        throw new Error('CST: unsupported range policy "' + policy + '" — supported: clamp, pass.');
    }

    const sameGamut = inPrim === outPrim;
    const sameXfer = inXf === outXf;
    const vsMatIn = CST_MATRICES[inMat] ?? null;
    const vsRngIn = CST_RANGES[inRng] ?? null;
    const vsRngOut = CST_RANGES[outRng] ?? null;

    let py = '';
    py += '# ── CST (Color Space Transform) ───────────────────────────────\n';
    py += '# MANUAL transform — no auto detection (the OFX API exposes no\n';
    py += '# node-input color metadata). Operator-stated interpretation:\n';
    py += '#   in:  primaries=' + GAMUT_LABEL[inPrim] + ' · transfer=' + XFER_LABEL[inXf] + '\n';
    py += '#        YUV matrix=' + MAT_LABEL[inMat] + ' · range=' + inRng + '\n';
    py += '#   out: primaries=' + GAMUT_LABEL[outPrim] + ' · transfer=' + XFER_LABEL[outXf] + '\n';
    py += '#        YUV matrix=' + MAT_LABEL[outMat] + ' · range=' + outRng + '\n';
    if (sameGamut) py += '#   (primaries unchanged — no gamut matrix applied)\n';
    // CORRECTNESS (2026-11-05, correctness review C02 note): only claim "no curves" when we
    // actually skip them. When the transfer is unchanged but the GAMUT
    // changes, we still decode→(gamut)→encode — the matrix operates on LINEAR
    // light, so the roundtrip is required. When both are unchanged the
    // roundtrip is skipped entirely (exact identity, no float noise).
    const skipCurves = sameXfer && sameGamut;
    if (skipCurves) {
        py += '#   (transfer and primaries unchanged — no transfer curves applied)\n';
    } else if (sameXfer) {
        py += '#   (transfer unchanged — curves applied as a decode/gamut/encode roundtrip: the matrix operates on linear light)\n';
    }
    py += '# Out-of-range policy: ' + (policy === 'clamp'
        ? 'clamp samples to [0,1] BEFORE the transfer curves AND AFTER the gamut matrix '
        + '(gamut conversion can push otherwise-valid wide-gamut colors negative — encoding '
        + 'a negative at fractional power is NaN; both boundaries are clamped)'
        : 'PASS through — transfer curve math is undefined outside [0,1]; PQ/HLG/pow WILL misbehave '
        + 'on out-of-range samples (advanced, opt-in)') + '.\n';
    py += '# Float precision throughout (RGBS); duration/FPS/dims unchanged.\n';
    py += 'def _vsres_cst(c):\n';

    // 1. YUV → RGBS float decode (only when the arriving clip is YUV/gray).
    const miArgs = vsMatIn ? ", matrix_in_s='" + vsMatIn + "'" : '';
    const riArgs = vsRngIn ? ", range_in_s='" + vsRngIn + "'" : '';
    py += '    if c.format.color_family != vs.RGB:\n';
    py += "        c = core.resize.Bicubic(c, format=vs.RGBS" + miArgs + riArgs + ")\n";

    // 2. Range policy.
    if (policy === 'clamp') {
        py += "    c = core.std.Expr(c, ['x 0 max 1 min', 'x 0 max 1 min', 'x 0 max 1 min'])\n";
    }

    // 3. Transfer decode → linear (skipped when both transfer and gamut are
    // unchanged — see skipCurves above).
    const dec = CST_TRANSFERS[inXf].decode;
    if (dec && !skipCurves) {
        py += "    c = core.std.Expr(c, ['" + dec + "', '" + dec + "', '" + dec + "'])  # "
            + XFER_LABEL[inXf] + ' → linear\n';
    }

    // 4. Gamut 3×3 (plane-mixing via ShufflePlanes — verified pattern).
    if (!sameGamut) {
        const key = inPrim + '>' + outPrim;
        const M = CST_GAMUT_PAIRS[key];
        if (!M) {
            throw new Error('CST: no verified gamut pair for ' + GAMUT_LABEL[inPrim] + ' → '
                + GAMUT_LABEL[outPrim] + ' (pair "' + key + '" missing from the verified table). '
                + 'Supported gamuts: ' + CST_GAMUTS.map(g => GAMUT_LABEL[g]).join(', ') + '.');
        }
        py += '    # Gamut: ' + GAMUT_LABEL[inPrim] + ' → ' + GAMUT_LABEL[outPrim] + ' (published-verified 3×3)\n';
        py += '    _p = [core.std.ShufflePlanes(c, planes=_i, colorfamily=vs.GRAY) for _i in range(3)]\n';
        for (let i = 0; i < 3; i++) {
            const e = M[i][0] + ' x * ' + M[i][1] + ' y * + ' + M[i][2] + ' z * +';
            py += "    _r" + i + " = core.std.Expr(_p, ['" + e + "'])\n";
        }
        py += '    c = core.std.ShufflePlanes([_r0, _r1, _r2], planes=[0, 0, 0], colorfamily=vs.RGB)\n';
        // CORRECTNESS (2026-11-05, correctness review C03): clamp AFTER the gamut matrix too.
        // A valid Rec.2020 saturated red converts to [1.66, -0.125, -0.018] in
        // Rec.709 — the pre-transfer clamp alone leaves those negatives to hit
        // BT.1886's fractional pow and produce NaN. The clamp policy applies at
        // EVERY boundary where curve math expects [0,1].
        if (policy === 'clamp') {
            py += "    c = core.std.Expr(c, ['x 0 max 1 min', 'x 0 max 1 min', 'x 0 max 1 min'])\n";
        }
    }

    // 5. Transfer encode (linear → signal) — gated by skipCurves like decode.
    const enc = CST_TRANSFERS[outXf].encode;
    if (enc && !skipCurves) {
        py += "    c = core.std.Expr(c, ['" + enc + "', '" + enc + "', '" + enc + "'])  # linear → "
            + XFER_LABEL[outXf] + '\n';
    }

    // 6. Output encode: RGB (keep float RGBS) or YUV (matrix/range/subsampling).
    if (outMat === 'rgb') {
        py += '    return c  # keep RGB (float RGBS)\n';
    } else {
        const fmt = CST_OUT_FORMATS[outSub];
        const msArgs = ", matrix_s='" + CST_MATRICES[outMat] + "'";
        const rsArgs = vsRngOut ? ", range_s='" + vsRngOut + "'" : '';
        py += "    return core.resize.Bicubic(c, format=vs." + fmt + msArgs + rsArgs + ")\n";
    }
    py += 'clip = _vsres_cst(clip)\n';
    return py;
}

export function cstTemplateBody(): string {
    return emitCstBody({ ...CST_DEFAULT_PARAMS });
}